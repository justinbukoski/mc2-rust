    fn quantizer_classes_and_requantized_ranges_match_annex_b() {
        let expected_steps = [
            3, 5, 7, 9, 15, 31, 63, 127, 255, 511, 1023, 2047, 4095, 8191, 16383, 32767, 65535,
        ];
        assert_eq!(QUANT_CLASSES.map(|class| class.steps), expected_steps);
        for class in QUANT_CLASSES {
            assert_eq!(class.grouped, matches!(class.steps, 3 | 5 | 9));
            assert!(class.code_bits > 0 && class.code_bits <= 16);
            for code in 0..u32::from(class.steps) {
                let sample = super::super::dequantize(code, class);
                assert!(
                    (-1.0..=1.0).contains(&sample),
                    "{}-step class code {code} requantized to {sample}",
                    class.steps
                );
            }
        }
    }

    #[test]
    fn synthesis_window_pins_normative_coefficients_and_is_symmetric() {
        assert_eq!(SYNTHESIS_WINDOW.len(), 512);
        for (index, expected) in [
            (0, 0.0),
            (1, -0.000_015_259),
            (63, -0.003_173_828),
            (64, 0.003_250_122),
            (128, 0.031_082_153),
            (255, -1.144_287_1),
            (256, 1.144_989),
            (447, -0.003_326_416),
            (448, 0.003_250_122),
            (511, 0.000_015_259),
        ] {
            assert_eq!(
                SYNTHESIS_WINDOW[index], expected,
                "window coefficient {index}"
            );
        }
        for i in 1..256 {
            let sign = if i % 64 == 0 { 1.0 } else { -1.0 };
            assert!(
                (SYNTHESIS_WINDOW[i] - sign * SYNTHESIS_WINDOW[512 - i]).abs() <= 1e-9,
                "window symmetry at index {i}"
            );
        }
    }
