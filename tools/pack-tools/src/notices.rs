//! `gen-notices TARGET_TRIPLE OUT_FILE`: third-party license notices for the shipped binary.
//!
//! The cargo-about equivalent: walks `cargo metadata --filter-platform TARGET --locked` from the
//! `mc2-app` package over normal and build dependencies only (no dev-dependencies), and writes every
//! crate outside the workspace with its version, SPDX license expression, repository and the full text
//! of its license files, sorted, so the output is deterministic for a given Cargo.lock.
//! Run from rust/. The only input is Cargo.lock plus the registry sources cargo already downloaded.
use crate::{io, universal_newlines, Result};
use serde_json::Value;
use std::collections::{HashMap, HashSet};
use std::path::Path;

/// File-name prefixes (lower case) that mark a license file.
const LIC: [&str; 7] = [
    "license",
    "licence",
    "copying",
    "copyright",
    "notice",
    "unlicense",
    "patents",
];

pub fn cargo_metadata(target: &str) -> Result<Value> {
    let out = std::process::Command::new("cargo")
        .args([
            "metadata",
            "--format-version",
            "1",
            "--locked",
            "--filter-platform",
            target,
        ])
        .stderr(std::process::Stdio::inherit())
        .output()
        .map_err(|e| format!("cargo metadata: {e}"))?;
    if !out.status.success() {
        return Err(format!("cargo metadata failed: {}", out.status));
    }
    serde_json::from_slice(&out.stdout).map_err(|e| format!("cargo metadata: {e}"))
}

/// Python's truthiness for an optional JSON string: absent, null and "" are all "no value".
fn text<'a>(p: &'a Value, key: &str) -> Option<&'a str> {
    p.get(key).and_then(Value::as_str).filter(|s| !s.is_empty())
}

/// `str.strip()`: Unicode white space plus the four ASCII separators U+001C..U+001F.
fn py_strip(s: &str) -> &str {
    s.trim_matches(|c: char| c.is_whitespace() || ('\u{1c}'..='\u{1f}').contains(&c))
}

fn field<'a>(v: &'a Value, key: &str) -> Result<&'a Value> {
    v.get(key)
        .ok_or_else(|| format!("cargo metadata: missing \"{key}\""))
}

fn name_version(p: &Value) -> (String, String) {
    (
        p["name"].as_str().unwrap_or("").to_string(),
        p["version"].as_str().unwrap_or("").to_string(),
    )
}

/// The notices file for the parsed `cargo metadata`, and the number of crates in it.
pub fn notices_text(meta: &Value, target: &str) -> Result<(String, usize)> {
    let packages = field(meta, "packages")?
        .as_array()
        .ok_or("cargo metadata: packages")?;
    let by_id: HashMap<&str, &Value> = packages
        .iter()
        .filter_map(|p| Some((p.get("id")?.as_str()?, p)))
        .collect();
    let nodes = field(field(meta, "resolve")?, "nodes")?
        .as_array()
        .ok_or("cargo metadata: nodes")?;
    let by_node: HashMap<&str, &Value> = nodes
        .iter()
        .filter_map(|n| Some((n.get("id")?.as_str()?, n)))
        .collect();
    let root = packages
        .iter()
        .find(|p| p.get("name").and_then(Value::as_str) == Some("mc2-app"))
        .and_then(|p| p.get("id")?.as_str())
        .ok_or("cargo metadata: no mc2-app package")?;
    let mut seen: HashSet<&str> = HashSet::new();
    let mut stack = vec![root];
    while let Some(id) = stack.pop() {
        if !seen.insert(id) {
            continue;
        }
        let node = by_node
            .get(id)
            .ok_or_else(|| format!("cargo metadata: no node {id}"))?;
        for dep in field(node, "deps")?
            .as_array()
            .ok_or("cargo metadata: deps")?
        {
            let kinds = field(dep, "dep_kinds")?
                .as_array()
                .ok_or("cargo metadata: dep_kinds")?;
            let normal_or_build = |k: &Value| match k.get("kind") {
                None | Some(Value::Null) => true,
                Some(kind) => kind == "build",
            };
            if kinds.iter().any(normal_or_build) {
                stack.push(field(dep, "pkg")?.as_str().ok_or("cargo metadata: pkg")?);
            }
        }
    }
    let workspace: HashSet<&str> = field(meta, "workspace_members")?
        .as_array()
        .ok_or("cargo metadata: workspace_members")?
        .iter()
        .filter_map(Value::as_str)
        .collect();
    let mut crates: Vec<&Value> = Vec::new();
    for id in &seen {
        if !workspace.contains(id) {
            crates.push(
                by_id
                    .get(id)
                    .ok_or_else(|| format!("cargo metadata: no package {id}"))?,
            );
        }
    }
    crates.sort_by_key(|p| name_version(p));
    let mut lines: Vec<String> = vec![
        format!("THIRD-PARTY NOTICES (generated by pack-tools gen-notices for {target})"),
        "This program is under the Microsoft Shared Source Limited Permissive License (Ms-SSLPL), see LICENSE-MS-SSLPL.txt."
            .into(),
        "The crates below are linked into the program.".into(),
        format!("{} crates.", crates.len()),
        String::new(),
    ];
    for p in &crates {
        let (name, version) = name_version(p);
        lines.push("=".repeat(78));
        lines.push(format!("{name} {version}"));
        let license = text(p, "license")
            .or_else(|| text(p, "license_file"))
            .unwrap_or("UNSPECIFIED");
        lines.push(format!("license: {license}"));
        let source = text(p, "repository")
            .or_else(|| text(p, "source"))
            .unwrap_or("-");
        lines.push(format!("source: {source}"));
        if license.contains("MPL") {
            // MPL-2.0 requires pointing at the exact source of the covered files.
            lines.push(format!(
                "source code (MPL-2.0 covered files): https://crates.io/crates/{name}/{version}"
            ));
        }
        lines.push(String::new());
        let manifest = field(p, "manifest_path")?
            .as_str()
            .ok_or("cargo metadata: manifest_path")?;
        let dir = Path::new(manifest)
            .parent()
            .ok_or("cargo metadata: manifest_path")?;
        let mut files: Vec<String> = Vec::new();
        for entry in io(std::fs::read_dir(dir), dir)? {
            let entry = io(entry, dir)?;
            let Ok(file_name) = entry.file_name().into_string() else {
                continue;
            };
            if entry.path().is_file()
                && LIC
                    .iter()
                    .any(|prefix| file_name.to_lowercase().starts_with(prefix))
            {
                files.push(file_name);
            }
        }
        files.sort();
        if files.is_empty() {
            lines.push("(no license file in the crate; see the SPDX expression above)".into());
        }
        for f in files {
            lines.push(format!("--- {f} ---"));
            let bytes = io(std::fs::read(dir.join(&f)), dir.join(&f))?;
            lines.push(py_strip(&universal_newlines(&String::from_utf8_lossy(&bytes))).to_string());
            lines.push(String::new());
        }
        lines.push(String::new());
    }
    Ok((lines.join("\n"), crates.len()))
}

pub fn run(target: &str, out: &Path) -> Result<()> {
    let (text, n) = notices_text(&cargo_metadata(target)?, target)?;
    io(std::fs::write(out, text), out)?;
    println!("{}: {n} crates", out.display());
    Ok(())
}
