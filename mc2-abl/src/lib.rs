//! ABL, the scripting language of MechCommander 2 mission scripts and AI brains.
//!
//! This crate is a faithful port of the compiler and interpreter in `mclib/abl*.cpp`:
//!
//! * [`scanner`] - tokens, comments, `#include_` / `#print_on` style directives, reserved words;
//! * `parser` (internal) - the type-checking compiler producing [`ast`] trees, with module/library symbol tables,
//!   `static` / `eternal` storage, arrays, `fsm` / `state` / `trans`, `order` functions and library calls;
//! * [`interp`] - the executor, including the order-completion protocol and FSM transition loop;
//! * [`mod@env`] - the environment ([`Env`]): module and library registry, instances, limits ([`Config`]);
//! * [`natives`] - the [`GameBindings`] trait with every game function registered in `code/ablmc2.cpp`
//!   (generated by `oracle-tools gen-natives`) and [`NullBindings`].
//!
//! Typical use:
//!
//! ```
//! use mc2_abl::*;
//! let mut src = MemorySource::new();
//! src.insert("data/missions/demo.abl", "module demo : integer;\ncode\n  return(7);\nendmodule.\n");
//! let mut env = Env::new(Config::default(), src, Box::new(DefaultHost));
//! let handle = env.pre_process("data/missions/demo.abl").unwrap();
//! let inst = env.new_instance(handle).unwrap();
//! env.execute(inst, &mut NullBindings).unwrap();
//! assert_eq!(env.get_integer(inst), 7);
//! ```

